function generateMarkdown(): string {
  const date = new Date().toISOString().split("T")[0];
  let md = `# Application Route & API Endpoint Inventory\n\n`;
  md += `**Generated:** ${date} (Auto-generated by \`scripts/generate-route-inventory.ts\`)\n`;
  md += `**Standard:** OWASP API9:2023 Compliance\n\n`;
  md += `## 1. Frontend Client Routes (${routes.length})\n\n`;
  md += `| Route Path | Description | Access Level | Auth Required |\n`;
  md += `| :--- | :--- | :--- | :---: |\n`;
  for (const r of routes) {
    md += `| \`${r.path}\` | ${r.description} | ${r.access} | ${r.authRequired ? "Yes" : "No"} |\n`;
  }

  md += `\n## 2. External Webhooks & API Endpoints (${externalEndpoints.length})\n\n`;
  md += `| Endpoint | Type | External Consumer | Never-Delete Protected |\n`;
  md += `| :--- | :--- | :--- | :---: |\n`;
  for (const e of externalEndpoints) {
    md += `| \`${e.endpoint}\` | ${e.type} | ${e.externalConsumer} | ${e.neverDelete ? "**YES**" : "No"} |\n`;
  }

  return md;
}

