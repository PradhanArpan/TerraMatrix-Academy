// Helper functions for exam management
export function loadExamTracks(): ExamTrack[] {
  return EXAM_TRACKS;
}

export function loadExamQuestions(trackId?: string, topic?: string): ExamQuestion[] {
  return EXAM_QUESTIONS.filter((q) => {
    if (trackId && trackId !== "all" && q.trackId !== trackId) return false;
    if (topic && topic !== "All" && q.topic !== topic) return false;
    return true;
  });
}

export function shuffleQuestions<T>(array: T[]): T[] {
  const copy = [...array];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

export function saveUserExamAttempt(attempt: ExamAttemptResult): void {
  try {
    const raw = localStorage.getItem("terramatrix_exam_attempts") || "[]";
    const attempts: ExamAttemptResult[] = JSON.parse(raw);
    attempts.unshift(attempt);
    localStorage.setItem("terramatrix_exam_attempts", JSON.stringify(attempts.slice(0, 50)));
  } catch (err) {
    console.error("Failed to save exam attempt", err);
  }
}

export function loadUserExamAttempts(userEmail?: string): ExamAttemptResult[] {
  try {
    const raw = localStorage.getItem("terramatrix_exam_attempts") || "[]";
    const attempts: ExamAttemptResult[] = JSON.parse(raw);
    if (!userEmail) return attempts;
    return attempts.filter((a) => a.userEmail.toLowerCase() === userEmail.toLowerCase());
  } catch {
    return [];
  }
}
